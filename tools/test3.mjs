import { chromium } from 'playwright';
import fs from 'fs';
const [,, w = '390', h = '844', out = 'tools/n', mobile = '1'] = process.argv;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, deviceScaleFactor: mobile === '1' ? 2 : 1, hasTouch: mobile === '1', isMobile: mobile === '1' });
const p = await ctx.newPage();
const logs = [];
p.on('console', m => { if (m.type() !== 'log') logs.push(m.type() + ': ' + m.text()); });
p.on('pageerror', e => logs.push('PAGEERROR: ' + e.message + '\n' + (e.stack||'').split('\n').slice(0,3).join('\n')));
await p.route('https://cdn.jsdelivr.net/npm/three@0.160.0/**', route => { const u = new URL(route.request().url()); route.fulfill({ body: fs.readFileSync('/home/claude/kbs/node_modules/three/' + u.pathname.replace('/npm/three@0.160.0/', '')), contentType: 'application/javascript' }); });
await p.route('https://fonts.googleapis.com/**', route => route.fulfill({ body: '', contentType: 'text/css' }));
await p.goto('file:///home/claude/kbs/dist/jelajah-kbs.local.html');
await p.waitForTimeout(4500);
const ev = (js) => p.evaluate(js);
const shot = async (n) => { await p.screenshot({ path: `${out}-${n}.png` }); };
await ev(`document.querySelector('[data-q="qr-gerbang"]').click()`); await p.waitForTimeout(3500);
console.log('calls', await ev(`__jelajah.S.renderer.info.render.calls + ' tris ' + __jelajah.S.renderer.info.render.triangles`));
await ev(`document.querySelector('[data-z="komodo"]').click()`); await p.waitForTimeout(4000); await shot('komodo');
await ev(`document.querySelector('[data-demo="close"]').click()`); await p.waitForTimeout(6000); await shot('close');
await ev(`document.querySelector('#fab-night').click()`); await p.waitForTimeout(5000); await shot('night');
await ev(`document.querySelector('[data-z="gajah"]').click()`); await p.waitForTimeout(4000); await shot('gajah');
console.log(logs.slice(0, 20).join('\n') || 'no errors');
await b.close();
