import { chromium } from 'playwright';
import fs from 'fs';
const [,, w = '1440', h = '900', out = 'tools/t1'] = process.argv;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, deviceScaleFactor: 1 });
const p = await ctx.newPage();
const logs = [];
p.on('console', m => { if (m.type() !== 'log') logs.push(m.type() + ': ' + m.text()); });
p.on('pageerror', e => logs.push('PAGEERROR: ' + e.message + '\n' + (e.stack||'').split('\n').slice(0,3).join('\n')));
await p.route('https://cdn.jsdelivr.net/npm/three@0.160.0/**', route => { const u = new URL(route.request().url()); route.fulfill({ body: fs.readFileSync('/home/claude/kbs/node_modules/three/' + u.pathname.replace('/npm/three@0.160.0/', '')), contentType: 'application/javascript' }); });
await p.route('https://fonts.googleapis.com/**', route => route.fulfill({ body: '', contentType: 'text/css' }));
await p.goto('file:///home/claude/kbs/dist/jelajah-kbs.local.html');
await p.waitForTimeout(5000);
await p.screenshot({ path: out + '-a.png' }); console.log('LOAD LOGS:', logs.join('\n'));
await p.click('[data-q="qr-gerbang"]');
await p.waitForTimeout(3500);
await p.screenshot({ path: out + '-b.png' });
await p.evaluate(() => document.querySelector('[data-demo="komodo"]') ? document.querySelector('[data-demo="komodo"]').click() : null);
await p.waitForTimeout(3000);
await p.screenshot({ path: out + '-c.png' });
console.log(logs.slice(0, 20).join('\n') || 'no errors');
await b.close();
